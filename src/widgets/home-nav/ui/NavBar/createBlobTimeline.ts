/** 한 모양에서 다음 모양까지(초) — 일렁이는 속도는 이 값 하나가 정한다 */
const LEG = 1.0;

/** 일렁임 — 모양을 한 바퀴 돌고 첫 모양으로 돌아와 이음매 없이 반복한다 */
export const createBlobTimeline = (
  path: SVGPathElement
): gsap.core.Timeline => {
  const timeline = gsap.timeline({ repeat: -1 });

  [...BLOB_SHAPES.slice(1), BLOB_SHAPES[0]].forEach((shape) => {
    timeline.to(path, { morphSVG: shape, duration: LEG, ease: 'sine.inOut' });
  });

  // 모양 한 바퀴에 회전도 한 바퀴 — 주기를 맞춰야 두 운동의 박자가 어긋나 보이지 않는다
  // svgOrigin 은 좌표계 원점이다. 모양을 전부 원점에 맞춰 뒀으니 여기가 곧 덩어리 중심이다
  timeline.to(
    path,
    {
      rotation: 360,
      duration: timeline.duration(),
      ease: 'none',
      svgOrigin: '0 0',
    },
    0
  );

  // 시작 위상을 흩는다 — 같은 박자로 시작하면 덩어리가 옮겨 앉을 때마다 같은 모양을 보인다
  return timeline.progress(gsap.utils.random(0, 1));
};
